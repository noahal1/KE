// Generates src/data/fit-enums.ts from fit-file-parser's pinned Garmin FIT SDK
// profile (mirrors the workflow of generate-body-model.cjs). Run after
// upgrading the fit-file-parser dependency:
//
//   npm run gen-fit-enums
//
// We only need three enum tables at runtime to turn a strength-training set
// message's numeric (category, category_subtype) pair into a readable
// exercise name: exercise_category, *_exercise_name and set_type.
const fs = require("fs");
const path = require("path");
const { pathToFileURL } = require("url");

const profilePath = path.join(
  __dirname, "..", "node_modules", "fit-file-parser", "dist", "garmin_profile.generated.js",
);

// The profile module is ESM (package "type": "module"), so load it via a
// dynamic import from this CJS context. Windows needs a file:// URL.
import(pathToFileURL(profilePath).href)
  .then(({ GARMIN_TYPES, GARMIN_PROFILE_VERSION }) => {
    if (!GARMIN_TYPES || !GARMIN_TYPES.exercise_category) {
      throw new Error("exercise_category table missing from Garmin profile");
    }

    const pick = (name) => (GARMIN_TYPES[name] ? sortKeys(GARMIN_TYPES[name]) : undefined);

    // All "<category>_exercise_name" tables keyed by category string.
    const nameTables = {};
    for (const [key, table] of Object.entries(GARMIN_TYPES)) {
      if (key.endsWith("_exercise_name")) nameTables[key] = sortKeys(table);
    }

    const out = {
      _profile: `${GARMIN_PROFILE_VERSION.major}.${GARMIN_PROFILE_VERSION.minor}.${GARMIN_PROFILE_VERSION.patch}`,
      exercise_category: pick("exercise_category"),
      exercise_name_tables: nameTables,
      set_type: pick("set_type"),
      fit_base_unit: pick("fit_base_unit"),
    };

    const ts = `// Generated by scripts/generate-fit-enums.cjs — DO NOT EDIT MANUALLY.
// Source: fit-file-parser (pinned Garmin FIT SDK profile ${out._profile}).
// Regenerate with \`npm run gen-fit-enums\` after upgrading the parser.

export const FIT_EXERCISE_CATEGORIES: Record<string, string> = ${json(out.exercise_category)};

export const FIT_EXERCISE_NAME_TABLES: Record<string, Record<string, string>> = ${json(out.exercise_name_tables)};

export const FIT_SET_TYPE: Record<string, string> = ${json(out.set_type)};

export const FIT_BASE_UNIT: Record<string, string> = ${json(out.fit_base_unit)};
`;

    const dest = path.join(__dirname, "..", "src", "data", "fit-enums.ts");
    fs.writeFileSync(dest, ts);
    console.log(
      `fit-enums.ts written: ${Object.keys(out.exercise_category).length} categories,` +
      ` ${Object.keys(nameTables).length} name tables, ${countNames(nameTables)} names`,
    );
  })
  .catch((e) => {
    console.error("generation failed:", e);
    process.exit(1);
  });

function sortKeys(table) {
  return Object.fromEntries(
    Object.entries(table).sort((a, b) => Number(a[0]) - Number(b[0])),
  );
}

function countNames(tables) {
  return Object.values(tables).reduce((n, t) => n + Object.keys(t).length, 0);
}

function json(v) {
  return JSON.stringify(v, null, 2);
}
